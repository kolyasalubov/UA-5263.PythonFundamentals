"""
Task 3. Функція, яка рахує кількість кожного символу в рядку.

Опис рішення:
- Функція count_chars(text) створює порожній словник result.
- Проходжу циклом for по кожному символу рядка.
- result.get(char, 0) повертає поточну кількість символу або 0, якщо
  символ зустрівся вперше. Додаю 1 і записую назад у словник.
- Повертаю словник: ключ - символ, значення - скільки разів він є в рядку.
- Приклад: "hello" -> {"h": 1, "e": 1, "l": 2, "o": 1}
"""


def count_chars(text):
    """Повертає словник {символ: кількість} для заданого рядка."""
    result = {}
    for char in text:
        result[char] = result.get(char, 0) + 1
    return result


print(count_chars("hello"))  # {'h': 1, 'e': 1, 'l': 2, 'o': 1}
print(count_chars("banana"))  # {'b': 1, 'a': 3, 'n': 2}
print(count_chars(""))        # {}
